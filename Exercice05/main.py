def sum(a, b):
    """
    Add two numbers and return the result
    
    Parameters:
    
        a (int or float) : first number
        b (int or float) : second number
    
    Returns:
        int or float : Sum of the two numbers
    """
    return a + b
 
def subtraction(a, b):
    """
    Substract two numbers and return the result
    
    Parameters:
    
        a (int or float) : first number
        b (int or float) : second number
    
    Returns:
        int or float : Substraction of the second number from the first
    """
    return a - b
